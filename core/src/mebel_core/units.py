"""Единицы измерения.

Внутри ядра все размеры — целые числа в десятых долях миллиметра (dmm).
Так нет ошибок округления: 0,1 мм — минимальный шаг (NFR-01).
Перевод в миллиметры — только при вводе и выводе.
"""

DMM_PER_MM = 10


def mm(value: float) -> int:
    """Миллиметры → десятые доли миллиметра."""
    return int(round(value * DMM_PER_MM))


def to_mm(value: int) -> float:
    """Десятые доли миллиметра → миллиметры (для вывода)."""
    return value / DMM_PER_MM
