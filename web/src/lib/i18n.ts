/** Счётные слова «Что в изделии»: рус — три формы (1 полка, 2 полки, 5 полок), узб — «5 ta javon». */
const COUNTED: Record<'door' | 'slidingDoor' | 'drawer' | 'shelf' | 'rod', { ru: [string, string, string]; uz: string }> = {
  door: { ru: ['дверь', 'двери', 'дверей'], uz: 'eshik' },
  slidingDoor: { ru: ['дверь-купе', 'двери-купе', 'дверей-купе'], uz: 'kupe eshik' },
  drawer: { ru: ['ящик', 'ящика', 'ящиков'], uz: 'tortma' },
  shelf: { ru: ['полка', 'полки', 'полок'], uz: 'javon' },
  rod: { ru: ['штанга', 'штанги', 'штанг'], uz: 'shtanga' },
};

export type CountedWord = keyof typeof COUNTED;

export function counted(lang: Lang, word: CountedWord, n: number): string {
  const w = COUNTED[word];
  if (lang === 'uz') return `${n} ta ${w.uz}`;
  const m10 = n % 10;
  const m100 = n % 100;
  const form = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2;
  return `${n}\u00A0${w.ru[form]}`;
}
